			<p>Rainbow D3 mới được ra mắt vào năm 1980, sự thay đổi mô hình lớn đầu tiên trong hai mươi năm. Với một động cơ mới, chạy mát hơn, D3 là chiếc Rainbow đầu tiên được phê duyệt cho “wet pick-up.”</p>
